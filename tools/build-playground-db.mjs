/* ---------------------------------------------------------------------------
   build-playground-db.mjs — reference/schema/*.sql  ->  site/assets/forge-db.js

   The playground runs a real SQLite engine (vendored WASM) in the browser, and
   it must work from file:// where fetch() is blocked. So the schema and seed are
   embedded in a plain <script> instead of being fetched.

   That creates the one thing this repository is most careful about: a SECOND
   COPY of something. The .sql files are the source of truth; this file is
   generated from them; and tools/doctor.mjs check `site/playground-db` fails the
   build if the generated copy is out of date. Never hand-edit forge-db.js.

     node tools/build-playground-db.mjs          # regenerate
     node tools/build-playground-db.mjs --check  # exit 1 if stale
--------------------------------------------------------------------------- */

import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const SOURCES = ["reference/schema/01-schema.sql", "reference/schema/02-seed.sql"];
const OUT = join(ROOT, "site/assets/forge-db.js");

const parts = [];
for (const rel of SOURCES) parts.push(await readFile(join(ROOT, rel), "utf8"));
const sql = parts.join("\n");
const hash = createHash("sha256").update(sql).digest("hex").slice(0, 16);

/* A template literal would be fragile — the SQL contains backticks in comments
   and ${} would be interpolated. JSON.stringify produces a safe single-line
   string literal with every quote and newline escaped. */
const body = `/* GENERATED by tools/build-playground-db.mjs — DO NOT EDIT.
   Source: ${SOURCES.join(", ")}
   sha256: ${hash}
   Run \`node tools/build-playground-db.mjs\` after changing the schema, or the
   integrity gate will fail. */
self.FORGE_DB_SQL = ${JSON.stringify(sql)};
self.FORGE_DB_HASH = ${JSON.stringify(hash)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = await readFile(OUT, "utf8"); } catch {}
  if (current !== body) {
    console.error("site/assets/forge-db.js is out of date. Run: node tools/build-playground-db.mjs");
    process.exit(1);
  }
  console.log("forge-db.js is current (" + hash + ")");
} else {
  await writeFile(OUT, body, "utf8");
  console.log(`wrote site/assets/forge-db.js — ${(sql.length / 1024).toFixed(1)} KB of SQL, hash ${hash}`);
}
